import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {copy,initialPoses,newSession,commitStage,type Manifest} from '../../src/core';
const KEY='chi-xu-workshop:challenge:v1';
test('画面内直接按当前视角移动，反馈即时出现，窄屏不用下滚',async({page})=>{
 await page.goto('/');await page.locator('[data-action="new"]').click();
 await page.locator('[data-action="intro-skip"]').click({timeout:60000});
 const panel=page.locator('#motion-controls'),forward=panel.locator('[data-action="motion-forward"]');
 await expect(panel).toBeVisible();await expect(page.locator('#motion-overlay')).toBeVisible();await expect(panel).toContainText('蓝色轮廓是目标');
 const raw=await page.evaluate(k=>JSON.parse(localStorage.getItem(k)!),KEY);
 await forward.click();await expect(panel.locator('[role="status"]')).toContainText('更接近目标');
 const after=await page.evaluate(k=>JSON.parse(localStorage.getItem(k)!).working.poses,KEY);
 expect(after['3'].translation).toEqual([.25,0,0]);
 expect(after['5']).toEqual(raw.working.poses['5']);
 await panel.locator('[data-action="motion-back"]').click();await expect(panel.locator('[role="status"]')).toContainText('离目标更远');
 const saved=await page.evaluate(k=>localStorage.getItem(k),KEY);
 await page.locator('[data-action="view-occlusal"]').click();
 await expect(forward).toContainText('向上挪');
 await expect(page.locator('#motion-overlay')).toHaveAttribute('data-forward','向上挪');
 await page.screenshot({path:'docs/screenshots/motion-translate-desktop.png',fullPage:true});
 await page.locator('[data-action="view-side"]').click();await expect(forward).toContainText('向右挪');
 expect(await page.evaluate(k=>localStorage.getItem(k),KEY)).toBe(saved);
 await page.setViewportSize({width:390,height:844});
 await expect(forward).toBeInViewport();await expect(panel).toBeInViewport();
 const controls=await panel.boundingBox(),viewport=await page.locator('#viewport').boundingBox();
 expect(controls!.y+controls!.height).toBeLessThan(viewport!.y+viewport!.height);
 await page.screenshot({path:'docs/screenshots/motion-translate-mobile.png',fullPage:true});
 await page.locator('aside [data-action="compare-before"]').click();await expect(panel).toBeHidden();await expect(page.locator('#motion-overlay')).toBeHidden();
});
test('第二关按真实轴旋转，弧线和顺逆时针名称一致并保留旧进度',async({page})=>{
 const m=JSON.parse(readFileSync('public/cases/initial/manifest.json','utf8')) as Manifest;
 const initial=initialPoses(m,Object.fromEntries(Object.entries(m.prepared_assets!).map(([id,a])=>[id,a.pivot])));
 const p=copy(initial);for(const [id,target] of Object.entries(m.levels[0].target_pose))p[id]={...copy(target),pivot:initial[id].pivot};
 const session=commitStage(newSession(m,initial),m,1,p,[],0,0);session.current_level=2;
 const record={signature:createHash('sha256').update(JSON.stringify(m)).digest('hex'),session};
 await page.goto('/');await page.evaluate(({k,v})=>localStorage.setItem(k,JSON.stringify(v)),{k:KEY,v:record});await page.reload();await page.locator('[data-action="continue"]').click();
 const panel=page.locator('#motion-controls');await expect(panel).toBeVisible({timeout:60000});
 await panel.locator('[data-action="motion-tool-rotate"]').click();
 await page.locator('[data-action="view-occlusal"]').click();
 await expect(panel.locator('[data-action="motion-forward"]')).toContainText('顺时针转');
 await expect(page.locator('#motion-overlay')).toHaveAttribute('data-tool','rotate');
 const before=copy(p);
 await panel.locator('[data-action="motion-forward"]').click();
 await expect(panel.locator('[role="status"]')).toContainText('更接近目标');
 const after=await page.evaluate(k=>JSON.parse(localStorage.getItem(k)!).working.poses,KEY);
 expect(after['4'].translation).toEqual(before['4'].translation);expect(after['4'].quaternion).not.toEqual(before['4'].quaternion);
 expect(after['3']).toEqual(p['3']);expect(after['5']).toEqual(p['5']);
 await page.screenshot({path:'docs/screenshots/motion-rotate-desktop.png',fullPage:true});
});
